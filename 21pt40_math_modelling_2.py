import numpy as np
import matplotlib.pyplot as plt

# Function to construct polynomial p_N(x) of degree 2N
def construct_polynomial(N):
    # Initialize coefficients for the polynomial of degree 2N
    coeffs = np.zeros(2 * N + 1)
    coeffs[0] = 1  # p_N(0) = 1

    # Define roots at x = j/N for j = 1, ..., N
    roots = np.array([j / N for j in range(1, N + 1)])

    # Create a system to enforce p_N(j/N) = 0
    # We need 2N equations, but we only have N roots + p_N(0) = 1
    # Instead, let's use a Lagrange interpolation approach with additional constraints
    x_points = np.concatenate(([0], roots))  # Include x = 0
    y_values = np.zeros(N + 1)
    y_values[0] = 1  # p_N(0) = 1

    # However, we need exactly degree 2N, so we'll adjust manually if needed
    coeffs = np.polyfit(x_points, y_values, 2 * N)

    return coeffs[::-1]

# Evaluate polynomial at points x
def evaluate_polynomial(coeffs, x):
    return np.polyval(coeffs[::-1], x)

N_values = [2, 4, 6, 8, 12, 20]
x = np.linspace(0, 1, 1000)

plt.figure(figsize=(10, 6))
for N in N_values:
    coeffs = construct_polynomial(N)
    p_N_x = evaluate_polynomial(coeffs, x)
    plt.plot(x, p_N_x, label=f'N = {N}')

plt.axhline(0, color='black', linewidth=0.5)
plt.axvline(0, color='black', linewidth=0.5)
plt.xlabel('x')
plt.ylabel('p_N(x)')
plt.title('Polynomial p_N(x) for Different N Values')
plt.legend()
plt.grid(True)
plt.show()

