import numpy as np
import matplotlib.pyplot as plt

def simulate_system(a0, r, steps):
    a = [a0]
    for n in range(steps):
        a.append((r**n) * a[-1])
    return a

np.random.seed(42)

examples_per_case = 5

case_definitions = [
    ("i) r = 0", lambda: 0),
    ("ii) 0 < r < 1", lambda: np.random.uniform(0.01, 0.99)),
    ("iii) -1 < r < 0", lambda: np.random.uniform(-0.99, -0.01)),
    ("iv) r > 1", lambda: 1 + np.random.uniform(0.01, 2)),
    ("v) r < -1", lambda: -1 - np.random.uniform(0.01, 2))
]

fig, axes = plt.subplots(len(case_definitions), 1, figsize=(12, 18))
if len(case_definitions) == 1:
    axes = [axes]

a0 = 0.5
min_steps = 100
max_steps = 200

for ax, (case_name, r_generator) in zip(axes, case_definitions):
    for _ in range(examples_per_case):
        r = r_generator()
        steps = np.random.randint(min_steps, max_steps)
        trajectory = simulate_system(a0, r, steps)
        ax.plot(trajectory, 'o-', markersize=3,
                label=f"r={r:.3f}, steps={steps}")

    ax.set_title(case_name)
    ax.set_xlabel('Time step (n)')
    ax.set_ylabel('State ($a_n$)')
    ax.legend()
    ax.grid(True)
    ax.axhline(0, color='black', linestyle='--', alpha=0.5)

