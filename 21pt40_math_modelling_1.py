import numpy as np
import matplotlib.pyplot as plt
from collections import deque

SIM_TIME = 1000
MEAN_INTER_ARRIVAL = 10
SERVICE_MIN = 8
SERVICE_MAX = 12
SERVICE_MEAN = 10

np.random.seed(42)

ARRIVAL = 'arrival'
DEPARTURE = 'departure'

event_queue = []
queue = deque()
system_state = []
wait_times = []
server_busy = False
server_busy_time = 0
current_time = 0
customer_id = 0
num_in_system = 0

inter_arrival = np.random.exponential(MEAN_INTER_ARRIVAL)
event_queue.append((inter_arrival, ARRIVAL, customer_id))
arrival_times = {}

while event_queue and current_time < SIM_TIME:
    event_queue.sort()
    time, event_type, cid = event_queue.pop(0)
    current_time = time

    if event_type == ARRIVAL:
        arrival_times[cid] = current_time
        num_in_system += 1
        system_state.append((current_time, num_in_system))

        if current_time < SIM_TIME:
            next_customer_id = customer_id + 1
            next_arrival_time = current_time + np.random.exponential(MEAN_INTER_ARRIVAL)
            event_queue.append((next_arrival_time, ARRIVAL, next_customer_id))
            customer_id += 1

        if not server_busy:
            server_busy = True
            service_time = np.random.poisson(SERVICE_MEAN)
            service_time = max(SERVICE_MIN, min(SERVICE_MAX, service_time))
            server_busy_time += service_time
            wait_times.append(0)
            event_queue.append((current_time + service_time, DEPARTURE, cid))
        else:
            queue.append(cid)

    elif event_type == DEPARTURE:
        num_in_system -= 1
        system_state.append((current_time, num_in_system))
        service_start = arrival_times[cid] if cid not in queue else current_time - service_time
        wait_time = service_start - arrival_times[cid]
        if wait_time > 0:
            wait_times[-1] = wait_time
        del arrival_times[cid]

        if queue:
            next_cid = queue.popleft()
            service_time = np.random.poisson(SERVICE_MEAN)
            service_time = max(SERVICE_MIN, min(SERVICE_MAX, service_time))
            server_busy_time += service_time
            wait_times.append(current_time - arrival_times[next_cid])
            event_queue.append((current_time + service_time, DEPARTURE, next_cid))
        else:
            server_busy = False

avg_wait_time = np.mean(wait_times) if wait_times else 0
avg_queue_length = sum(wt * len(queue) for wt in wait_times) / SIM_TIME if wait_times else 0
utilization = server_busy_time / SIM_TIME if SIM_TIME > 0 else 0

print(f"Average waiting time in queue: {avg_wait_time:.2f} minutes")
print(f"Average number of customers in queue: {avg_queue_length:.2f}")
print(f"Average utilization of booking station: {utilization:.2%}")

times, counts = zip(*system_state)
plt.step(times, counts, where='post')
plt.xlabel('Time (minutes)')
plt.ylabel('Number of Customers in System')
plt.title('Sample Path of Queueing System')
plt.grid(True)
plt.show()